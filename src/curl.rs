//! Turning a captured request into a `curl` command or a bash script that replays it.
//! Kept free of UI types.

use crate::har::{Entry, Header};

/// Larger bodies are written to a file next to the script rather than inlined
pub const MAX_INLINE_BODY_BYTES: usize = 32 * 1024;

/// Headers curl sets itself, or that would be wrong when replayed
const DROPPED_HEADERS: [&str; 2] = ["content-length", "accept-encoding"];

/// Header names (or parts of them) whose values are credentials
const SECRET_HEADER_PARTS: [&str; 8] = [
    "cookie",
    "auth",
    "token",
    "credential",
    "secret",
    "session",
    "api-key",
    "apikey",
];

/// The plain command, e.g. for the clipboard. Secrets stay inline, as in the browser's
/// "Copy as cURL"
pub fn command(entry: &Entry) -> Result<String, String> {
    let body = entry_body(entry);
    if body.is_some_and(|body| body.contains('\0')) {
        return Err("the body contains NUL bytes; save it as a script instead".to_string());
    }
    let invocation = invocation(entry, false, body.map(|body| BodyArg::Inline(body)));
    Ok(invocation.render(false))
}

/// A bash script replaying the request
pub struct Script {
    pub text: String,
    /// The body, when too large (or binary) to inline: it goes in a file next to the script
    pub body_file: Option<BodyFile>,
}

pub struct BodyFile {
    /// File name relative to the script's directory
    pub name: String,
    pub bytes: Vec<u8>,
}

/// The script for `entry` (`number` is 1-based, `source` is the HAR file it came from).
/// `script_name` is the script's file name, from which a body file's name is derived
pub fn script(entry: &Entry, number: usize, source: &str, script_name: &str) -> Script {
    let body = entry_body(entry);
    let body_file = body
        .filter(|body| body.len() > MAX_INLINE_BODY_BYTES || body.contains('\0'))
        .map(|body| BodyFile {
            name: body_file_name(script_name),
            bytes: body.as_bytes().to_vec(),
        });
    let body_arg = match (&body_file, body) {
        (Some(_), _) => Some(BodyArg::File),
        (None, Some(body)) => Some(BodyArg::Inline(body)),
        (None, None) => None,
    };
    let invocation = invocation(entry, true, body_arg);

    let mut text = String::from("#!/usr/bin/env bash\n");
    text.push_str(&format!(
        "# Replays entry {} of {}: {} {}\n",
        number,
        printable(source),
        printable(&entry.request.method),
        entry.request.url
    ));
    text.push_str(&format!(
        "# Captured {}; generated by harview\n",
        printable(&entry.started_date_time)
    ));
    text.push_str(&format!(
        "# Extra curl options can be passed as arguments, e.g. {} -i\n",
        printable(script_name)
    ));
    text.push_str("set -euo pipefail\n");

    if !invocation.secrets.is_empty() {
        text.push_str("\n# Credentials captured in the HAR; override them from the environment, e.g.\n");
        text.push_str(&format!(
            "#   {}='...' {}\n",
            invocation.secrets[0].0,
            printable(script_name)
        ));
        for (variable, value) in &invocation.secrets {
            text.push_str(&format!("{}=${{{}:-{}}}\n", variable, variable, quote(value)));
        }
    }
    if let Some(body_file) = &body_file {
        text.push_str(&format!(
            "\nBODY_FILE=\"$(dirname \"$0\")\"/{}\n",
            quote(&body_file.name)
        ));
    }
    text.push('\n');
    text.push_str(&invocation.render(true));
    text.push('\n');

    Script { text, body_file }
}

/// `exports/0012-host-login-request.sh` → `0012-host-login-request.body`
fn body_file_name(script_name: &str) -> String {
    let file_name = script_name.rsplit('/').next().unwrap_or(script_name);
    let stem = file_name.strip_suffix(".sh").unwrap_or(file_name);
    format!("{}.body", stem)
}

fn entry_body(entry: &Entry) -> Option<&str> {
    entry
        .request
        .post_data
        .as_ref()
        .map(|post_data| post_data.text.as_str())
        .filter(|text| !text.is_empty())
}

enum BodyArg<'a> {
    Inline(&'a str),
    /// Read from `$BODY_FILE`
    File,
}

struct Invocation {
    url: String,
    /// One option (with its value) per line, ready for the shell
    options: Vec<String>,
    /// Variables for credential headers: (name, captured value)
    secrets: Vec<(String, String)>,
}

impl Invocation {
    /// One option per line; a script also passes its own arguments on to curl
    fn render(&self, script: bool) -> String {
        let mut lines = vec![format!("curl {}", self.url)];
        lines.extend(self.options.iter().map(|option| format!("  {}", option)));
        if script {
            lines.push("  \"$@\"".to_string());
        }
        lines.join(" \\\n")
    }
}

fn invocation(entry: &Entry, secrets_as_variables: bool, body: Option<BodyArg>) -> Invocation {
    let request = &entry.request;
    let mut options = Vec::new();
    let mut secrets: Vec<(String, String)> = Vec::new();

    let method = request.method.to_ascii_uppercase();
    match method.as_str() {
        "HEAD" => options.push("--head".to_string()),
        // curl sends GET, or POST when there is a body
        "GET" if body.is_none() => {}
        "POST" if body.is_some() => {}
        _ if request.method.chars().all(|c| c.is_ascii_alphanumeric()) => {
            options.push(format!("-X {}", request.method))
        }
        _ => options.push(format!("-X {}", quote(&request.method))),
    }

    let mut compressed = false;
    for header in &request.headers {
        let name = header.name.to_ascii_lowercase();
        if name == "accept-encoding" {
            compressed = true;
        }
        if is_dropped(header, &request.url) {
            continue;
        }
        if secrets_as_variables && is_secret(&name) {
            let variable = unique_variable(&variable_name(&header.name), &secrets);
            options.push(format!(
                "-H \"{}: ${{{}}}\"",
                double_quote_escape(&header.name),
                variable
            ));
            secrets.push((variable, header.value.clone()));
        } else {
            options.push(format!("-H {}", quote(&format!("{}: {}", header.name, header.value))));
        }
    }
    // Without one, curl would label the body application/x-www-form-urlencoded
    let has_content_type = request
        .headers
        .iter()
        .any(|header| header.name.eq_ignore_ascii_case("content-type"));
    if let Some(post_data) = request.post_data.as_ref().filter(|_| body.is_some()) {
        if !has_content_type && !post_data.mime_type.is_empty() {
            options.push(format!("-H {}", quote(&format!("Content-Type: {}", post_data.mime_type))));
        }
    }
    if compressed {
        options.push("--compressed".to_string());
    }

    match body {
        Some(BodyArg::Inline(text)) if method != "HEAD" => {
            options.push(format!("--data-raw {}", quote(text)))
        }
        Some(BodyArg::File) if method != "HEAD" => {
            options.push("--data-binary \"@$BODY_FILE\"".to_string())
        }
        _ => {}
    }

    Invocation {
        url: quote(request.url.as_str()),
        options,
        secrets,
    }
}

/// HTTP/2 pseudo-headers, headers curl computes itself, and a `Host` that matches the URL
fn is_dropped(header: &Header, url: &url::Url) -> bool {
    let name = header.name.to_ascii_lowercase();
    if name.starts_with(':') || DROPPED_HEADERS.contains(&name.as_str()) {
        return true;
    }
    if name == "host" {
        let authority = match (url.host_str(), url.port()) {
            (Some(host), Some(port)) => format!("{}:{}", host, port),
            (Some(host), None) => host.to_string(),
            (None, _) => String::new(),
        };
        return header.value.eq_ignore_ascii_case(&authority);
    }
    false
}

fn is_secret(lowercase_name: &str) -> bool {
    SECRET_HEADER_PARTS
        .iter()
        .any(|part| lowercase_name.contains(part))
}

/// `x-ms-refreshtokencredential` → `X_MS_REFRESHTOKENCREDENTIAL`
fn variable_name(header_name: &str) -> String {
    let name: String = header_name
        .chars()
        .map(|c| if c.is_ascii_alphanumeric() { c.to_ascii_uppercase() } else { '_' })
        .collect();
    if name.starts_with(|c: char| c.is_ascii_digit()) || name.is_empty() {
        format!("H_{}", name)
    } else {
        name
    }
}

/// `COOKIE`, then `COOKIE_2`, ... for repeated headers (HTTP/2 may split cookies)
fn unique_variable(base: &str, taken: &[(String, String)]) -> String {
    let is_taken = |name: &str| taken.iter().any(|(variable, _)| variable == name);
    if !is_taken(base) {
        return base.to_string();
    }
    (2..)
        .map(|n| format!("{}_{}", base, n))
        .find(|name| !is_taken(name))
        .expect("an unused name")
}

/// Quotes `text` as one shell word: `'...'`, or ANSI-C `$'...'` when it holds control
/// characters (newlines, CRs in multipart bodies, ...) so the script stays readable and
/// editors can't mangle them
pub fn quote(text: &str) -> String {
    if !text.chars().any(|c| c.is_control()) {
        return format!("'{}'", text.replace('\'', r"'\''"));
    }
    let mut quoted = String::from("$'");
    for c in text.chars() {
        match c {
            '\\' => quoted.push_str(r"\\"),
            '\'' => quoted.push_str(r"\'"),
            '\n' => quoted.push_str(r"\n"),
            '\r' => quoted.push_str(r"\r"),
            '\t' => quoted.push_str(r"\t"),
            // Interactive bash may expand `!` in $'...' (history); \x21 is always literal
            '!' => quoted.push_str(r"\x21"),
            c if c.is_control() && (c as u32) < 0x80 => {
                quoted.push_str(&format!(r"\x{:02x}", c as u32))
            }
            c if c.is_control() => quoted.push_str(&format!(r"\u{:04x}", c as u32)),
            c => quoted.push(c),
        }
    }
    quoted.push('\'');
    quoted
}

/// For text inside `"..."`
fn double_quote_escape(text: &str) -> String {
    let mut escaped = String::new();
    for c in text.chars() {
        if matches!(c, '\\' | '"' | '$' | '`') {
            escaped.push('\\');
        }
        escaped.push(c);
    }
    escaped
}

/// For text in a `#` comment: control characters (e.g. a newline in a file name) would end it
fn printable(text: &str) -> String {
    text.chars()
        .map(|c| if c.is_control() { '?' } else { c })
        .collect()
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::har::Har;

    fn entry(json: &str) -> Entry {
        let har: Har = serde_json::from_str(&format!(r#"{{"log": {{"entries": [{}]}}}}"#, json))
            .expect("valid entry");
        har.log.entries.into_iter().next().expect("one entry")
    }

    fn request(method: &str, headers: &str, post_data: &str) -> Entry {
        entry(&format!(
            r#"{{"startedDateTime": "2026-10-17T10:00:00Z",
                "request": {{"method": "{}", "url": "https://api.example.com/v2/login?next=%2Fhome",
                             "httpVersion": "HTTP/1.1", "headers": [{}] {}}},
                "response": {{"status": 200, "content": {{}}}}}}"#,
            method, headers, post_data
        ))
    }

    fn post_data(mime_type: &str, text: &str) -> String {
        format!(
            r#", "postData": {{"mimeType": "{}", "text": {}}}"#,
            mime_type,
            serde_json::to_string(text).expect("json string")
        )
    }

    fn json_body(text: &str) -> String {
        post_data("application/json", text)
    }

    /// A body without a MIME type, so no Content-Type is added
    fn untyped_body(text: &str) -> String {
        post_data("", text)
    }

    const LOGIN_HEADERS: &str = r#"
        {"name": "Host", "value": "api.example.com"},
        {"name": "Content-Type", "value": "application/json"},
        {"name": "Content-Length", "value": "16"},
        {"name": "Accept-Encoding", "value": "gzip, br"},
        {"name": "Authorization", "value": "Bearer abc"},
        {"name": "Cookie", "value": "sid=1; theme=dark"}"#;

    #[test]
    fn quote_plain_text_in_single_quotes() {
        assert_eq!(quote("a b $HOME `x` \"y\" !z"), "'a b $HOME `x` \"y\" !z'");
    }

    #[test]
    fn quote_single_quote_is_closed_escaped_and_reopened() {
        assert_eq!(quote("it's"), r"'it'\''s'");
    }

    #[test]
    fn quote_control_characters_use_ansi_c_quoting() {
        assert_eq!(
            quote("a\r\nb\t'c'\\!\u{1}"),
            r"$'a\r\nb\t\'c\'\\\x21\x01'"
        );
    }

    #[test]
    fn quote_keeps_non_ascii_as_is() {
        assert_eq!((quote("café ✓"), quote("café\n")), ("'café ✓'".to_string(), r"$'café\n'".to_string()));
    }

    #[test]
    fn command_post_with_body_formats_like_devtools() {
        let entry = request("POST", LOGIN_HEADERS, &json_body(r#"{"user":"alice"}"#));

        let result = command(&entry);

        assert_eq!(
            result.as_deref(),
            Ok(concat!(
                "curl 'https://api.example.com/v2/login?next=%2Fhome' \\\n",
                "  -H 'Content-Type: application/json' \\\n",
                "  -H 'Authorization: Bearer abc' \\\n",
                "  -H 'Cookie: sid=1; theme=dark' \\\n",
                "  --compressed \\\n",
                "  --data-raw '{\"user\":\"alice\"}'"
            ))
        );
    }

    #[test]
    fn command_method_flag_only_when_curl_would_not_infer_it() {
        let commands = [
            command(&request("GET", "", "")),
            command(&request("GET", "", &untyped_body("x"))),
            command(&request("POST", "", "")),
            command(&request("DELETE", "", "")),
            command(&request("HEAD", "", "")),
        ]
        .map(|result| result.expect("command"));

        assert_eq!(
            commands,
            [
                "curl 'https://api.example.com/v2/login?next=%2Fhome'",
                "curl 'https://api.example.com/v2/login?next=%2Fhome' \\\n  -X GET \\\n  --data-raw 'x'",
                "curl 'https://api.example.com/v2/login?next=%2Fhome' \\\n  -X POST",
                "curl 'https://api.example.com/v2/login?next=%2Fhome' \\\n  -X DELETE",
                "curl 'https://api.example.com/v2/login?next=%2Fhome' \\\n  --head",
            ]
            .map(String::from)
        );
    }

    #[test]
    fn command_drops_pseudo_headers_and_keeps_a_differing_host() {
        let headers = r#"
            {"name": ":authority", "value": "api.example.com"},
            {"name": ":method", "value": "GET"},
            {"name": "host", "value": "other.example.com"},
            {"name": "accept", "value": "*/*"}"#;

        let result = command(&request("GET", headers, ""));

        assert_eq!(
            result.as_deref(),
            Ok(concat!(
                "curl 'https://api.example.com/v2/login?next=%2Fhome' \\\n",
                "  -H 'host: other.example.com' \\\n",
                "  -H 'accept: */*'"
            ))
        );
    }

    #[test]
    fn command_multiline_body_uses_ansi_c_quoting() {
        let result = command(&request("POST", "", &untyped_body("--b\r\nname=\"a\"\r\n--b--\r\n")));

        assert_eq!(
            result.as_deref(),
            Ok("curl 'https://api.example.com/v2/login?next=%2Fhome' \\\n  --data-raw $'--b\\r\\nname=\"a\"\\r\\n--b--\\r\\n'")
        );
    }

    #[test]
    fn command_adds_content_type_from_the_body_when_no_header_has_it() {
        let result = command(&request("POST", "", &json_body("{}")));

        assert_eq!(
            result.as_deref(),
            Ok(concat!(
                "curl 'https://api.example.com/v2/login?next=%2Fhome' \\\n",
                "  -H 'Content-Type: application/json' \\\n",
                "  --data-raw '{}'"
            ))
        );
    }

    #[test]
    fn command_refuses_nul_bytes() {
        let result = command(&request("POST", "", &json_body("a\0b")));

        assert!(result.is_err());
    }

    #[test]
    fn script_moves_credentials_into_overridable_variables() {
        let entry = request("POST", LOGIN_HEADERS, &json_body("{}"));

        let script = script(&entry, 12, "capture.har", "exports/0012-login-request.sh");

        assert_eq!(
            script.text,
            concat!(
                "#!/usr/bin/env bash\n",
                "# Replays entry 12 of capture.har: POST https://api.example.com/v2/login?next=%2Fhome\n",
                "# Captured 2026-10-17T10:00:00Z; generated by harview\n",
                "# Extra curl options can be passed as arguments, e.g. exports/0012-login-request.sh -i\n",
                "set -euo pipefail\n",
                "\n",
                "# Credentials captured in the HAR; override them from the environment, e.g.\n",
                "#   AUTHORIZATION='...' exports/0012-login-request.sh\n",
                "AUTHORIZATION=${AUTHORIZATION:-'Bearer abc'}\n",
                "COOKIE=${COOKIE:-'sid=1; theme=dark'}\n",
                "\n",
                "curl 'https://api.example.com/v2/login?next=%2Fhome' \\\n",
                "  -H 'Content-Type: application/json' \\\n",
                "  -H \"Authorization: ${AUTHORIZATION}\" \\\n",
                "  -H \"Cookie: ${COOKIE}\" \\\n",
                "  --compressed \\\n",
                "  --data-raw '{}' \\\n",
                "  \"$@\"\n",
            )
        );
    }

    #[test]
    fn script_detects_credentials_by_header_name_and_numbers_repeats() {
        let headers = r#"
            {"name": "x-ms-refreshtokencredential", "value": "r"},
            {"name": "cookie", "value": "a=1"},
            {"name": "cookie", "value": "b=2"},
            {"name": "x-api-key", "value": "k"},
            {"name": "accept", "value": "*/*"}"#;

        let script = script(&request("GET", headers, ""), 1, "a.har", "a.sh");
        let variables: Vec<_> = script
            .text
            .lines()
            .filter(|line| line.contains(":-"))
            .collect();

        assert_eq!(
            variables,
            [
                "X_MS_REFRESHTOKENCREDENTIAL=${X_MS_REFRESHTOKENCREDENTIAL:-'r'}",
                "COOKIE=${COOKIE:-'a=1'}",
                "COOKIE_2=${COOKIE_2:-'b=2'}",
                "X_API_KEY=${X_API_KEY:-'k'}",
            ]
        );
    }

    #[test]
    fn script_large_body_goes_to_a_file_next_to_the_script() {
        let large = "x".repeat(MAX_INLINE_BODY_BYTES + 1);

        let script = script(&request("PUT", "", &untyped_body(&large)), 3, "a.har", "exports/0003-up-request.sh");
        let body_file = script.body_file.expect("body file");

        assert_eq!(
            (
                body_file.name.as_str(),
                body_file.bytes.len(),
                script.text.contains("BODY_FILE=\"$(dirname \"$0\")\"/'0003-up-request.body'\n"),
                script.text.contains("  -X PUT \\\n  --data-binary \"@$BODY_FILE\" \\\n  \"$@\"\n"),
            ),
            ("0003-up-request.body", MAX_INLINE_BODY_BYTES + 1, true, true)
        );
    }

    #[test]
    fn script_comment_lines_cannot_be_broken_by_the_source_name() {
        let script = script(&request("GET", "", ""), 1, "evil\ntouch /tmp/x.har", "a.sh");

        assert!(script.text.contains("# Replays entry 1 of evil?touch /tmp/x.har: GET "));
    }

    #[test]
    fn variable_name_is_a_valid_shell_identifier() {
        assert_eq!(
            [variable_name("x-auth-token"), variable_name("1st-token")],
            ["X_AUTH_TOKEN".to_string(), "H_1ST_TOKEN".to_string()]
        );
    }
}
